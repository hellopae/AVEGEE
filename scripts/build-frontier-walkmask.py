#!/usr/bin/env python3
"""Encode owner's full-resolution white walkmask as alternating RLE (town mask format).
Usage: python3 scripts/build-frontier-walkmask.py /path/to/frontier12
Never modifies the source artwork or files in img/.
"""
import hashlib, json, sys, re
import numpy as np
from pathlib import Path
from PIL import Image
root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
im = Image.open(source / 'frontier12-walkmask.png').convert('L')
runs, current, count = [], 0, 0
for value in im.tobytes():
    value = int(value >= 128)
    if value == current: count += 1
    else: runs.append(count); current, count = value, 1
runs.append(count)
trees = [{k: t[k] for k in ('x','y','kind','big') if k in t} for t in json.loads((source / 'frontier12-trees.json').read_text())]
assert len(trees) == 80
out = '// GENERATED by scripts/build-frontier-walkmask.py; owner mask, white = walkable.\n'
out += '// Source PNG SHA256: ' + hashlib.sha256((source / 'frontier12-walkmask.png').read_bytes()).hexdigest() + '\n'
out += f'export const FRONTIER_WALK_COLS={im.width}, FRONTIER_WALK_ROWS={im.height};\n'
out += '// Alternating runs, row-major, starting blocked; one cell per source pixel.\n'
out += 'export const FRONTIER_WALK_RUNS=' + json.dumps(runs,separators=(',',':')) + ';\n'
out += 'export const FRONTIER_OWNER_TREES=Object.freeze(' + json.dumps(trees,separators=(',',':')) + '.map(Object.freeze));\n'
# Compile the unchanged corridor/pads fallback too, rather than rasterizing at startup.
geometry = (root / 'src/route-geometry.js').read_text()
def array(name):
    value = re.search(name + r' = Object.freeze\((\[.*?\])\.map', geometry)[1]
    return json.loads(re.sub(r'(?<=[\[,])\.', '0.', value))
corridor, pads = array('FALLBACK_CORRIDOR'), array('PADS')
cols, rows = 836, 471
y, x = np.mgrid[:rows,:cols]; x=(x+.5)/cols; y=(y+.5)/rows
inside = np.zeros((rows,cols),dtype=bool)
for a,b,rx,ry in pads: inside |= ((x-a)/rx)**2+((y-b)/ry)**2<=1
for a,b in zip(corridor,corridor[1:]):
    dx,dy=b[0]-a[0],b[1]-a[1]; u=np.clip(((x-a[0])*dx+(y-a[1])*dy)/(dx*dx+dy*dy),0,1)
    inside |= (x-a[0]-u*dx)**2+(y-a[1]-u*dy)**2<=.026**2
fallback=[]; current=count=0
for v in inside.ravel():
    if v==current: count+=1
    else: fallback.append(count); current=int(v); count=1
fallback.append(count)
out += 'export const FRONTIER_CORRIDOR_MASK={cols:836,rows:471,runs:' + json.dumps(fallback,separators=(',',':')) + '};\n'
(root / 'src/frontier-walkmask-th-asia.js').write_text(out)
print('encoded', im.size, len(runs), 'runs;', len(trees), 'trees')
