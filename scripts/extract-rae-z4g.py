#!/usr/bin/env python3
"""T8c: copy the scenes, lines and the window of Rae's part D, section 7 (walking back through the frontiers · fire and controlled reapers · freeing Zones 3 -> 2 -> 1)
VERBATIM into src/z4g-raw.js - never retyped.
  python3 scripts/extract-rae-z4g.py "<Output/Rae/2026-11-19-avegee-r2d-zone4-end.md>"
Parsed by shape (js blocks as they are; the window and the two single lines by their labels); an assert fails loudly if a shape changes."""
import sys, re, json
from pathlib import Path
L = Path(sys.argv[1]).read_text(encoding='utf-8').split('\n')
def idx(prefix, start=0): return next(i for i in range(start, len(L)) if L[i].startswith(prefix))
def clean(s): return s.replace("\\'", "'").strip()
S7, S8 = idx('## 7. '), idx('## 8. ')
def blocks(a, b):
    out = []; i = a
    while i < b:
        if L[i].startswith('```js'):
            j = i + 1
            while not L[j].startswith('```'): j += 1
            out.append('\n'.join(L[i + 1:j])); i = j
        i += 1
    return out
bl = blocks(S7, S8)
assert len(bl) == 5, len(bl)
page2, fire3, fire21, rest3, rest21 = bl
assert page2.lstrip().startswith('{ title:{ th:\'ไปทีละโซน') and "'z3-fire'" in fire3 and "'z2-fire'" in fire21 and "'z1-fire'" in fire21 and "'z3-restored'" in rest3 and "'z2-restored'" in rest21 and "'z1-restored'" in rest21
# T9 (Claudy ruling on Rae's question F1): the TH word for the lord who is UNDER control is "ผู้ถูกควบคุม" (the source line says "ผู้ครอบงำ", which means the one who controls) - the ONE deliberate edit of the verbatim copy
OLD_WORD, NEW_WORD = 'ผู้ครอบงำของแต่ละโซนพ่าย', 'ผู้ถูกควบคุมของแต่ละโซนพ่าย'
assert page2.count(OLD_WORD) == 1, 'source line changed'
page2 = page2.replace(OLD_WORD, NEW_WORD)
scenes = [fire3, fire21, rest3, rest21]
# ---- the single line of Lucifer at the colosseum on the way back (7.1)
lu = clean(next(l for l in L[S7:S8] if l.startswith('- ผ่านโคลอสเซียม')))
m = re.search(r'บรรทัดเดียว: "(.*?)" · EN Lucifer: "(.*?)" ', lu + ' '); assert m, lu
lucifer = { 'th':'ลูซิเฟอร์: "' + m.group(1) + '"', 'en':'Lucifer: "' + m.group(2) + '"' }
# ---- what a controlled reaper says when touched (7.2): `- ยมทูตที่ถูกควบคุมไม่สู้ (... แตะแล้วขึ้นบรรทัดสั้น "TH" TH/EN `EN`)`
tp = clean(next(l for l in L[S7:S8] if l.startswith('- ยมทูตที่ถูกควบคุมไม่สู้')))
m = re.search(r'"(ขวาง[^"]*)" TH/EN `([^`]*)`', tp); assert m, tp
tap = { 'th':m.group(1), 'en':m.group(2) }
# ---- NR-1: `- **NR-1 · ...** หัวข้อ: <TH> · EN: <EN> · ข้อความ: <TH> · EN: <EN> · ปุ่ม: <TH> · EN: <EN>`
nr = clean(next(l for l in L[S7:S8] if l.startswith('- **NR-1')))
m = re.match(r'^- \*\*NR-1[^*]*\*\*\s*หัวข้อ: (.*?) · EN: (.*?) · ข้อความ: (.*?) · EN: (.*?) · ปุ่ม: (.*?) · EN: (.*)$', nr); assert m, nr
notice = { 'th':{ 'title':m.group(1).strip(), 'text':m.group(3).strip(), 'button':m.group(5).strip() }, 'en':{ 'title':m.group(2).strip(), 'text':m.group(4).strip(), 'button':m.group(6).strip() } }
assert '<ชื่อโซน>' in notice['th']['title'] and '<Zone>' in notice['en']['title'], notice
out = ["// GENERATED by scripts/extract-rae-z4g.py from Output/Rae/2026-11-19-avegee-r2d-zone4-end.md (section 7) - Rae's text verbatim, do not edit by hand (T9: one deliberate word change, see OLD_WORD in the script).", ""]
out.append('/** the page that REPLACES page 2 of cyber-signal-win (the harbours are shut: the way back is on foot) */')
out.append('export const RAW_Z4G_SIGNAL_WIN_PAGE2 = ([\n' + page2 + '\n])[0];\n')
out.append('export const RAW_Z4G_SCENES = Object.assign({}, ' + ', '.join('({\n' + b + '\n})' for b in scenes) + ');\n')
for name, val in (('RAW_Z4G_LUCIFER_PASS', lucifer), ('RAW_Z4G_CONTROLLED_TAP', tap), ('RAW_Z4G_NR1', notice)):
    out.append(f'export const {name} = ' + json.dumps(val, ensure_ascii=False, indent=1) + ';\n')
Path(__file__).resolve().parent.parent.joinpath('src', 'z4g-raw.js').write_text('\n'.join(out), encoding='utf-8')
print('ok', lucifer, tap, notice['th']['title'])
