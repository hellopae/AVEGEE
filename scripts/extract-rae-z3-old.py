#!/usr/bin/env python3
"""T7b: copy the story blocks of Rae's FIRST Zone 3 script (the parts her part C says "use verbatim") into src/z3d-raw-old.js - never retyped.
  python3 scripts/extract-rae-z3-old.py "<path to Output/Rae/2026-11-15-avegee-z3-events.md>"
Each fenced block of `'key': {...}` scenes becomes one frozen constant named RAW_<first key>; a block's scenes are {title:{th,en}, pages:[{title:{th,en}, line:{th,en}}]}."""
import sys, re
from pathlib import Path
L = Path(sys.argv[1]).read_text(encoding='utf-8').split('\n')
out = ["// GENERATED by scripts/extract-rae-z3-old.py from Output/Rae/2026-11-15-avegee-z3-events.md - Rae's text verbatim, do not edit by hand.", ""]
i = 0; n = 0
while i < len(L):
    if L[i].startswith('```js'):
        j = i + 1
        while not L[j].startswith('```'): j += 1
        keys = [m.group(1) for l in L[i + 1:j] for m in [re.match(r"^'([a-z0-9-]+)': \{", l)] if m]
        if keys and keys[0] in ('z3-eirlin-open', 'z3-eirlin-win', 'z3-sev-open', 'z3-jorm-yields', 'z3-sev-win'):
            name = 'RAW_OLD_' + keys[0].replace('-', '_').upper()
            out.append(f"export const {name} = ({{\n" + '\n'.join(L[i + 1:j]) + "\n});\n"); n += 1
        i = j
    i += 1
Path(__file__).resolve().parent.parent.joinpath('src', 'z3d-raw-old.js').write_text('\n'.join(out), encoding='utf-8'); print('blocks', n)
