// Rewrites src/soul-pose-manifest.js from the files that really sit in img/soul-poses/.
//   node scripts/soul-pose-manifest.mjs          write
//   node scripts/soul-pose-manifest.mjs --check  exit 1 if the manifest is out of date
// Drop a new <archetype>-<zone>-{scared,cry}-v1.webp in img/soul-poses/, run this, commit both.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const root = new URL('..', import.meta.url);
const files = readdirSync(new URL('img/soul-poses/', root)).filter(f => f.endsWith('.webp')).sort();
const text = `// GENERATED by scripts/soul-pose-manifest.mjs — do not edit. Lists the pose drawings that exist (so the game never requests a missing file).
export const SOUL_POSE_FILES = new Set([
${files.map(f => `  'img/soul-poses/${f}',`).join('\n')}
]);
`;
const target = new URL('src/soul-pose-manifest.js', root);
if (process.argv.includes('--check')) {
  let now = ''; try { now = readFileSync(target, 'utf8'); } catch {}
  if (now !== text) { console.error('src/soul-pose-manifest.js is out of date — run: node scripts/soul-pose-manifest.mjs'); process.exit(1); }
} else { writeFileSync(target, text); console.log(`${files.length} files`); }
