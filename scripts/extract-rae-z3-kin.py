"""T7c: copy the relatives' cases of Zone 3 (Rae) VERBATIM into src/z3g-raw-kin.js - the six case objects, the arrival notices and the KIN talk (before / during / after the verdict, the two choices and what each says).
Sources: the first Zone 3 script (sections 5.1-5.4, 7.1 = relatives 1-4 and 6; the case of relative 5) and part C section 6.2 (relative 5's NEW notice and talk with Van Helsing in place of the gate giant).
  python3 scripts/extract-rae-z3-kin.py "<Output/Rae/2026-11-15-avegee-z3-events.md>" "<Output/Rae/2026-11-19-avegee-r2c-zone3.md>"
Prose bullets are parsed by their shape: `  - speaker: "text"` + `    EN speaker: "text"`; choices `- ทางเลือก ...: **[A]** / **[B]**` + `  EN: ...` + `  - (label) line · line` + `    EN line · line`."""
import sys, re, json
from pathlib import Path
old = Path(sys.argv[1]).read_text(encoding='utf-8').split('\n'); new = Path(sys.argv[2]).read_text(encoding='utf-8').split('\n')
def clean(s): return s.replace("\\'", "'").rstrip()
def section(L, start_pat, end_pats):
    a = next(i for i, l in enumerate(L) if re.match(start_pat, l)); b = len(L)
    for i in range(a + 1, len(L)):
        if any(re.match(p, L[i]) for p in end_pats): b = i; break
    return L[a:b]
def field(lines, label):
    for l in lines:
        m = re.match(r'^- ' + re.escape(label) + r': (.*)$', l)
        if m: return clean(m.group(1))
    raise SystemExit('missing ' + label)
def notice(lines):
    i = next(i for i, l in enumerate(lines) if l.startswith('**NK'))
    blk = lines[i + 1:i + 9]
    return { 'th':{ 'title':field(blk, 'หัวข้อ'), 'text':field(blk, 'ข้อความ'), 'button':field(blk, 'ปุ่ม') }, 'en':{ 'title':field(blk, 'EN หัวข้อ'), 'text':field(blk, 'EN ข้อความ'), 'button':field(blk, 'EN ปุ่ม') } }
def talk(lines):
    i = next(i for i, l in enumerate(lines) if re.match(r'^\*\*บท(คดีญาติ \(KIN\)| KIN)', l))
    out = { 'before':{ 'th':[], 'en':[] }, 'during':{ 'th':[], 'en':[] }, 'after':{ 'th':[], 'en':[] }, 'choices':[] }
    cur = None; mode = None; labels = None; k = i + 1
    while k < len(lines):
        l = lines[k]
        if l.startswith('- ช่วงก่อนขึ้นแท่น'): cur = 'before'
        elif l.startswith('- ช่วงระหว่างไต่สวน'): cur = 'during'
        elif l.startswith('- ช่วงหลังตัดสิน'): cur = 'after'
        elif l.startswith('- ทางเลือก'):
            cur = None; mode = 'choice'
            labels = re.findall(r'\*\*\[(.*?)\]\*\*', l); en_labels = re.findall(r'\*\*\[(.*?)\]\*\*', lines[k + 1]); k += 1
            for a, b in zip(labels, en_labels): out['choices'].append({ 'label':{ 'th':clean(a), 'en':clean(b) }, 'lines':{ 'th':[], 'en':[] } })
        elif mode == 'choice':
            m = re.match(r'^  - \((.*?)\) (.*)$', l)
            if m:
                idx = len(out['choices']) and next(i2 for i2, c in enumerate(out['choices']) if not c['lines']['th'])
                out['choices'][idx]['lines']['th'] = [clean(x) for x in m.group(2).split(' · ')]
                en = lines[k + 1]; assert en.startswith('    EN '), en[:60]
                out['choices'][idx]['lines']['en'] = [clean(x) for x in en[len('    EN '):].split(' · ')]; k += 1
            elif l.startswith('  - **') or l.startswith('**') or l.startswith('---') or l.startswith('###') or l.startswith('หมายเหตุ'): break
        elif cur and l.startswith('  - ') and not l.startswith('  - **'):
            en = lines[k + 1]; assert en.startswith('    EN '), (cur, l[:50], en[:50])
            out[cur]['th'].append(clean(l[4:])); out[cur]['en'].append(clean(en[len('    EN '):])); k += 1
        k += 1
    assert all(c['lines']['th'] and len(c['lines']['th']) == len(c['lines']['en']) for c in out['choices']), 'choice lines'
    for p in ('before', 'during', 'after'): assert out[p]['th'] and len(out[p]['th']) == len(out[p]['en']), p
    return out
def case_block(L, key):
    i = 0
    while i < len(L):
        if L[i].startswith('```js') and L[i + 1].startswith('{') and f"k:'{key}'" in L[i + 2]:
            j = i + 1
            while not L[j].startswith('```'): j += 1
            return '\n'.join(L[i + 1:j])
        i += 1
    raise SystemExit('case not found ' + key)
END = [r'^### ', r'^## ']
rows = [('falseorder', old, r'^### 5\.1 '), ('youngerbrother', old, r'^### 5\.2 '), ('doomclient', old, r'^### 5\.3 '), ('carerdaughter', old, r'^### 5\.4 '), ('gatesentry', new, r'^### 6\.2 '), ('soupcook', old, r'^### 7\.1 ')]
data = {}; cases = {}
for key, L, pat in rows:
    sec = section(L, pat, END); data[key] = { 'notice':notice(sec), **talk(sec) }
    cases[key] = case_block(old, key)
js = ["// GENERATED by scripts/extract-rae-z3-kin.py from Rae's Zone 3 scripts (2026-11-15 sections 5.1-5.4 + 7.1, 2026-11-19 part C 6.2 for the sentry) - her text verbatim, do not edit by hand.", ""]
js.append('export const RAW_KIN = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')
for key, body in cases.items(): js.append(f"export const RAW_KINCASE_{key.upper()} = (\n{body}\n);\n")
Path(__file__).resolve().parent.parent.joinpath('src', 'z3g-raw-kin.js').write_text('\n'.join(js), encoding='utf-8')
print({k: (len(v['before']['th']), len(v['during']['th']), len(v['after']['th']), [len(c['lines']['th']) for c in v['choices']]) for k, v in data.items()})
