#!/usr/bin/env python3
"""Zone 1 walk mask: art-src/zone1-walkmask-v2.png (480x320, white = walkable, 1 cell = 8 world units)
-> src/town-walkmask.js (run-length encoded). Edit the PNG in any image editor, then re-run:
    python3 scripts/build-town-walkmask.py
Requires Pillow. The PNG is traced against img/map-zone1/v2 (plazas, roads, stairs, bridges, dock)."""
import json, sys
from pathlib import Path
from PIL import Image
root = Path(__file__).resolve().parent.parent
im = Image.open(root / 'art-src' / 'zone1-walkmask-v2.png').convert('L')
cols, rows = im.size
cells = [1 if v >= 128 else 0 for v in im.tobytes()]
runs, cur, n = [], 0, 0
for v in cells:
    if v == cur: n += 1
    else: runs.append(n); cur, n = v, 1
runs.append(n)
assert sum(runs) == cols * rows
out = ("// GENERATED by scripts/build-town-walkmask.py from art-src/zone1-walkmask-v2.png - do not edit by hand.\n"
       "// Zone 1 walkable ground (plazas, roads, stairs, bridges, dock) traced on img/map-zone1/v2. 1 cell = 8 world units.\n"
       f"export const TOWN_WALK_CELL=8,TOWN_WALK_COLS={cols},TOWN_WALK_ROWS={rows};\n"
       "// Alternating run lengths, row-major, starting with a run of blocked cells.\n"
       f"export const TOWN_WALK_RUNS={json.dumps(runs, separators=(',', ':'))};\n")
(root / 'src' / 'town-walkmask.js').write_text(out)
print('wrote src/town-walkmask.js', len(runs), 'runs')
