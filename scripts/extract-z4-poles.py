#!/usr/bin/env python3
"""Z4-POLES: read the owner's markup (Map-Zone4-2.jpg, 2500x1667) into src/z4-poles-data.js.

  dark navy (38,33,98) verticals = poles      -> shaft = opening with a 16x4 vertical kernel, foot = shaft bottom
  bright cyan (0,172,236) curves = wires      -> for every nearby pole pair, fit a parabola droop that best follows the
                                                 cyan pixels; keep pairs with >=90% coverage, <=230 px, then drop
                                                 a long wire when two shorter wires through a middle pole already exist.
usage: python3 scripts/extract-z4-poles.py <Map-Zone4-2.jpg> <out.js> [overlay.png]    (~3 min)
"""
import sys, json
import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage as ndi

src, out = sys.argv[1], sys.argv[2]
overlay = sys.argv[3] if len(sys.argv) > 3 else None
im = Image.open(src).convert('RGB')
b = np.asarray(im).astype(int); r, g, bl = b[..., 0], b[..., 1], b[..., 2]
H, W = r.shape

# ---- poles
m = (abs(r - 38) < 10) & (abs(g - 34) < 10) & (abs(bl - 98) < 12)
m = ndi.binary_closing(m, structure=np.ones((3, 3)))
lab, _ = ndi.label(ndi.binary_opening(m, structure=np.ones((16, 4))), structure=np.ones((3, 3)))
P = []
for i, s in enumerate(ndi.find_objects(lab)):
    w = s[1].stop - s[1].start
    if (lab[s] == i + 1).sum() < 60 or w > 16: continue
    P.append(dict(x=(s[1].start + s[1].stop) / 2, yb=s[0].stop, yt=s[0].start))

# ---- wires
cy = (r < 40) & (abs(g - 172) < 22) & (abs(bl - 236) < 20)
dist = ndi.distance_transform_edt(~cy)
t = np.linspace(0, 1, 36); k = (t >= .12) & (t <= .88); tk = t[k]
sf = np.arange(-0.06, 0.34, 0.02)[:, None]
def curve(a, c, off, dxa, dxb, N=None):
    x0, y0, x1, y1 = a['x'] + dxa, a['yt'] + off, c['x'] + dxb, c['yt'] + off
    return x0, y0, x1, y1, np.hypot(x1 - x0, y1 - y0)
def best(a, c):
    res = (0,)
    for off in (0, 8, 16, 26):
        for dxa in (-12, 0, 12):
            for dxb in (-12, 0, 12):
                x0, y0, x1, y1, dd = curve(a, c, off, dxa, dxb)
                x = x0 + (x1 - x0) * tk[None, :] + 0 * sf
                y = y0 + (y1 - y0) * tk[None, :] + sf * dd * 4 * tk[None, :] * (1 - tk[None, :])
                sc = (dist[np.clip(y.round().astype(int), 0, H - 1), np.clip(x.round().astype(int), 0, W - 1)] <= 4).mean(1)
                j = sc.argmax()
                if sc[j] > res[0]: res = (float(sc[j]), off, dxa, dxb, float(sf[j, 0]))
    return res
raw = []
for i in range(len(P)):
    for j in range(i + 1, len(P)):
        a, c = P[i], P[j]
        d = float(np.hypot(a['x'] - c['x'], a['yt'] - c['yt']))
        if d < 35 or d > 230: continue
        s = best(a, c)
        if s[0] >= .9: raw.append((i, j, d) + s)
adj = {}
for w in raw: adj.setdefault(w[0], set()).add(w[1]); adj.setdefault(w[1], set()).add(w[0])
def pts(w, N=60):
    i, j, d, sc, off, dxa, dxb, s = w
    x0, y0, x1, y1, dd = curve(P[i], P[j], off, dxa, dxb)
    u = np.linspace(0, 1, N)
    return x0 + (x1 - x0) * u, y0 + (y1 - y0) * u + s * dd * 4 * u * (1 - u)
keep = []
for w in raw:
    x, y = pts(w)
    if any(np.hypot(x[10:50] - P[q]['x'], y[10:50] - (P[q]['yt'] + 8)).min() < 22 for q in adj[w[0]] & adj[w[1]]): continue
    keep.append(w)

# ---- write (poles ordered top-to-bottom so ids are stable)
order = sorted(range(len(P)), key=lambda i: (round(P[i]['yb'] / 40), P[i]['x'])); rank = {o: n for n, o in enumerate(order)}
poles = [[round(P[o]['x'] / W, 4), round(P[o]['yb'] / H, 4), round((P[o]['yb'] - P[o]['yt']) / H, 4)] for o in order]
wires = sorted([min(rank[w[0]], rank[w[1]]), max(rank[w[0]], rank[w[1]]), round(w[7], 3)] for w in keep)
open(out, 'w').write('''// Z4-POLES: electric poles + wires of Zone 4, read from the owner's markup (Output/Claudy/zone4/input/Map-Zone4-2.jpg,
// dark-blue verticals = poles, light-blue curves = wires). Coordinates are 0-1 of the zone-4 map (any resolution).
// poles: [x, yBase, height] (height = drawn pole height, fraction of map height) · wires: [poleA, poleB, sag] (sag = droop / chord).
// Generated by scripts/extract-z4-poles.py; edit by hand only to add/remove a pole or wire.
export const Z4_POLES = Object.freeze(%s.map(p=>Object.freeze(p)));
export const Z4_WIRES = Object.freeze(%s.map(w=>Object.freeze(w)));
''' % (json.dumps(poles, separators=(',', ':')), json.dumps(wires, separators=(',', ':'))))
print(len(poles), 'poles', len(wires), 'wires')
if overlay:
    d = ImageDraw.Draw(im)
    for w in keep: x, y = pts(w); d.line(list(zip(x, y)), fill=(255, 255, 0), width=3)
    for p in P: d.ellipse([p['x'] - 5, p['yb'] - 5, p['x'] + 5, p['yb'] + 5], outline=(255, 0, 255), width=3)
    im.resize((1500, 1000)).save(overlay)
