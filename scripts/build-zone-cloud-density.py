#!/usr/bin/env python3
"""Zone 2 / 3 / 4 floating-cloud density: where the painted mist / cloud sea is, the drifting code-made clouds (src/zone-clouds.js) are allowed to show; over plazas, roads and
buildings they fade out.  Reads each zone's ground preview (read-only) and writes src/zone-clouds-density.js: a 48 x 32 grid per zone, one hex digit (0-f) per cell.
Nothing is drawn onto or filtered over the art; this only tells the clouds where to gather.
  python3 scripts/build-zone-cloud-density.py [--debug <dir>]   (debug = a heat-map overlay png per zone)"""
import sys, os
from PIL import Image, ImageFilter
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COLS, ROWS = 48, 32
SRC = {'asia': 'img/map-zone2/v8/zone2-terrain-v7-preview.webp', 'west': 'img/map-zone3/v7/zone3-terrain-v7-preview.webp', 'cyberhell': 'img/map-zone4/v7/zone4-terrain-v7-preview.webp'}
def hsv(a):
    im = Image.fromarray(a.astype('uint8')).convert('HSV'); h = np.asarray(im, float); return h[..., 0] * 360 / 255, h[..., 1] / 255, h[..., 2] / 255
def mist(zone, a):
    h, s, v = hsv(a)
    if zone == 'asia': m = (s < .24) & (v > .78)                                             # white / ivory sea of cloud between the peaks (stone is darker, v < .7)
    elif zone == 'west': m = (s < .2) & (v > .8)                                             # snow-cloud: the whitest, flattest pixels (snow on cliffs is broken up; blurred below)
    else: m = (h > 255) & (h < 325) & (s > .18) & (s < .62) & (v > .42) & (v < .86)           # violet smog (crystals are saturated and bright, rock is dark)
    return m.astype(float)
def grid(zone):
    a = np.asarray(Image.open(os.path.join(ROOT, SRC[zone])).convert('RGB'), float)
    m = Image.fromarray((mist(zone, a) * 255).astype('uint8')).filter(ImageFilter.GaussianBlur(26))
    small = np.asarray(m.resize((COLS, ROWS), Image.BILINEAR), float) / 255
    d = np.clip((small - .06) / .5, 0, 1) ** .8
    top = np.clip(1 - np.arange(ROWS) / ROWS * 4.5, 0, 1)[:, None] * .45                      # the far ridge always carries a little cloud
    d = np.clip(np.maximum(d, top * (1 if zone != 'west' else .6)), 0, 1)
    return d
out = ['// Floating-cloud density of zones 2-4, generated by scripts/build-zone-cloud-density.py from the ground previews. Do not edit by hand.',
       '// %d x %d cells over the whole map, one hex digit per cell (0 = no cloud, f = thickest).' % (COLS, ROWS), 'export const ZONE_CLOUD_COLS=%d, ZONE_CLOUD_ROWS=%d;' % (COLS, ROWS), 'export const ZONE_CLOUD_GRID=Object.freeze({']
dbg = sys.argv[sys.argv.index('--debug') + 1] if '--debug' in sys.argv else None
for z in SRC:
    d = grid(z); rows = [''.join('0123456789abcdef'[int(round(v * 15))] for v in r) for r in d]
    out.append('  %s:Object.freeze([\n%s\n  ]),' % (z, ',\n'.join("    '%s'" % r for r in rows)))
    print(z, 'mean density %.3f' % d.mean())
    if dbg:
        os.makedirs(dbg, exist_ok=True); im = Image.open(os.path.join(ROOT, SRC[z])).convert('RGB').resize((768, 512))
        hm = Image.fromarray((d * 255).astype('uint8')).resize((768, 512), Image.BILINEAR).convert('RGB')
        Image.blend(im, hm, .55).save(os.path.join(dbg, z + '-cloud-density.png'))
out.append('});')
out.append('''/** Cloud density 0..1 of `zone` at map fraction (u,v), bilinear over the grid (0 for an unknown zone). */
export function zoneCloudDensity(zone,u,v){
  const g=ZONE_CLOUD_GRID[zone]; if(!g)return 0;
  const x=Math.min(ZONE_CLOUD_COLS-1.001,Math.max(0,u*ZONE_CLOUD_COLS-.5)),y=Math.min(ZONE_CLOUD_ROWS-1.001,Math.max(0,v*ZONE_CLOUD_ROWS-.5));
  const x0=Math.floor(x),y0=Math.floor(y),fx=x-x0,fy=y-y0,at=(i,j)=>parseInt(g[j][i],16)/15;
  return (at(x0,y0)*(1-fx)+at(x0+1,y0)*fx)*(1-fy)+(at(x0,y0+1)*(1-fx)+at(x0+1,y0+1)*fx)*fy;
}''')
open(os.path.join(ROOT, 'src/zone-clouds-density.js'), 'w').write('\n'.join(out) + '\n')
