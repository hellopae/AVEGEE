def encode(im):
    runs=[]; on=0; n=0
    for v in im.tobytes():
        v=int(v>0)
        if v==on:n+=1
        else:runs.append(n); on=v; n=1
    runs.append(n)
    return runs

def main():
    from scipy.ndimage import distance_transform_edt, binary_dilation
    import numpy as np
    OUT.mkdir(parents=True,exist_ok=True)
    mask=Image.new('L',(W,H));d=ImageDraw.Draw(mask)
    for polygon in POLYGONS:d.polygon(polygon,fill=255)
    mask=mask.filter(ImageFilter.MinFilter(5))
    mask.save(OUT/'walkmask-after.png')
    old=(ROOT/'src/frontier-walkmask-th-asia.js').read_text()
    trees=json.loads(re.search(r'FRONTIER_OWNER_TREES=Object.freeze\((\[.*?\])\.map',old)[1])
    # Keep overlay roots at least 12px beyond the traced floor when relocation is needed.
    bank_exclusion=binary_dilation(np.array(mask)>0,iterations=12)
    _,indices=distance_transform_edt(bank_exclusion,return_indices=True)
    moved=[]
    for t in trees:
        x,y=int(t['x']*W),int(t['y']*H)
        if mask.getpixel((x,y)):
            by,bx=(int(indices[0,y,x]),int(indices[1,y,x]))
            moved.append({'before':[t['x'],t['y']],'after':[round((bx+.5)/W,7),round((by+.5)/H,7)]})
            t.update(x=round((bx+.5)/W,7),y=round((by+.5)/H,7))
        assert not mask.getpixel((int(t['x']*W),int(t['y']*H)))
    out='// Generated by scripts/build-border12-pilot.py; B12 v3 visible floor in normalized world coordinates.\n'
    out+='export const BORDER12_MASK='+json.dumps({'cols':W,'rows':H,'runs':encode(mask)},separators=(',',':'))+';\n'
    out+='export const BORDER12_TREES=Object.freeze('+json.dumps(trees,separators=(',',':'))+'.map(Object.freeze));\n'
    (ROOT/'src/frontier-walkmask-th-asia-b12.js').write_text(out)
    (OUT/'tree-relocations.json').write_text(json.dumps(moved,indent=2)+'\n')
    image=Image.open(ROOT/'img/frontier-route/zone1-2-v6.webp').convert('RGB')
    assert image.size==(3344,1882),image.size
    overlay=Image.new('RGBA',image.size,(0,230,190,0))
    overlay.putalpha(mask.resize(image.size,Image.Resampling.NEAREST).point(lambda v:95 if v else 0))
    result=Image.alpha_composite(image.convert('RGBA'),overlay)
    corridor=json.loads(re.search(r'DUNGEON_CORRIDOR = Object.freeze\((\[.*?\])\.map',(ROOT/'src/route-geometry.js').read_text())[1])
    dd=ImageDraw.Draw(result);dd.line([(x*image.width,y*image.height) for x,y in corridor],fill=(255,0,255),width=3)
    for i in [0,7,15,23,30]:
        x,y=corridor[i];x*=image.width;y*=image.height
        dd.ellipse((x-8,y-8,x+8,y+8),fill='white');dd.text((x+10,y),str(i),fill='black')
    result.convert('RGB').save(OUT/'overlay-after.png')
    original=Image.open(ROOT/'img/frontier-route/zone1-2-v5.webp').convert('RGB')
    compare=Image.new('RGB',(W,H*2));compare.paste(original,(0,0));compare.paste(image.resize((W,H),Image.Resampling.LANCZOS),(0,H));compare.save(OUT/'before-after.webp',quality=95)
    for name,box in [('bridge',(1070,350,1410,550)),('cave',(700,570,1070,750)),('west',(340,320,660,640))]:
        image.crop(tuple(v*2 for v in box)).save(OUT/f'zoom-native-{name}.png')
    (OUT/'art-metrics.json').write_text(json.dumps({'beforeSize':original.size,'afterSize':image.size,'canvasResolutionRatio':[image.width/original.width,image.height/original.height],'maskSize':mask.size,'coordinateSpace':'0–1 normalized; art resolution independent of navigation raster','assetSHA256':hashlib.sha256((ROOT/'img/frontier-route/zone1-2-v6.webp').read_bytes()).hexdigest()},indent=2)+'\n')
if __name__=='__main__':main()
