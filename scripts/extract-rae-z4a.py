#!/usr/bin/env python3
"""T8a: copy the scenes and tables of Rae's part D, sections 1-2 (border 3-4 + the colosseum + entering Zone 4 + HOME-67 at the harbour) VERBATIM into src/z4a-raw.js - never retyped.
  python3 scripts/extract-rae-z4a.py "<Output/Rae/2026-11-19-avegee-r2d-zone4-end.md>"
Scenes = every js block above section 3 (`'key': {title:{th,en}, pages:[...]}`) merged into RAW_Z4A_SCENES. Tables: the ten bouts of 1.5 (RAW_BOUTS: name / pre / win / move, each {th,en}) and the two helper tables 1.6-a / 1.7-a (RAW_HELPERS: thor / lucifer)."""
import sys, re, json
from pathlib import Path
L = Path(sys.argv[1]).read_text(encoding='utf-8').split('\n')
end3 = next(i for i, l in enumerate(L) if l.startswith('## 3. '))
blocks = []; i = 0
while i < end3:
    if L[i].startswith('```js'):
        j = i + 1
        while not L[j].startswith('```'): j += 1
        blocks.append('\n'.join(L[i + 1:j])); i = j
    i += 1
def clean(s): return s.replace("\\'", "'").strip()
def tr(cell):
    cell = clean(cell).replace('**', '')
    th, en = cell.split(' / ', 1) if ' / ' in cell else (cell, cell)
    return { 'th':th.strip().strip('"').strip(), 'en':en.strip().strip('"').strip() }
bouts = {}
a15 = next(i for i, l in enumerate(L) if l.startswith('### 1.5 ')); b15 = next(i for i, l in enumerate(L) if l.startswith('### 1.6 '))
for l in L[a15:b15]:
    m = re.match(r'^\| (\d+) \| (.*) \|$', l)
    if m and 1 <= int(m.group(1)) <= 8:
        cells = [c for c in re.split(r' \| ', m.group(2))]
        assert len(cells) == 4, (l[:60], len(cells))
        bouts[int(m.group(1))] = { 'name':tr(cells[0]), 'pre':tr(cells[1]), 'win':tr(cells[2]), 'move':tr(cells[3]) }
assert sorted(bouts) == list(range(1, 9)), sorted(bouts)
# T9 (Claudy): two status notes of Rae's to Toby are not part of the name / move - cut them out of the EN (the ONLY edits of the verbatim copy of the bouts)
for n, field, note in ((5, 'move', ' (ลดความเร็วทีม 1 รอบ)'), (2, 'name', ' (D3)')):
    assert bouts[n][field]['en'].endswith(note), (n, field, bouts[n][field]['en'])
    bouts[n][field]['en'] = bouts[n][field]['en'][:-len(note)]
# FB3-T8 (Rae R2 ฌ #25, Claudy ruling): the player-facing tower is now "หอส่องกรรม" - the ONLY other edit of the verbatim copy (the 2026-11-19 source file keeps the old word)
assert sum(b.count('หอกระจก') for b in blocks) == 1, 'z4-lumen-win: expected exactly one old tower name'
blocks = [b.replace('หอกระจก', 'หอส่องกรรม') for b in blocks]
LABELS = { 'ชื่อ':'name', 'ท่าไม้ตาย':'move', 'คำบรรยายท่า':'desc', 'ชนิดท่า (ข้อเสนอ)':'kind', 'บรรทัดตอนอัญเชิญ':'call', 'บรรทัดตอนใช้ท่า':'use', 'บรรทัดตอนจบท่า':'end' }
helpers = {}
for head, key in (('#### 1.6-ก ', 'thor'), ('#### 1.7-ก ', 'lucifer')):
    a = next(i for i, l in enumerate(L) if l.startswith(head)); rows = {}
    for l in L[a:a + 14]:
        m = re.match(r'^\| (.*?) \| (.*?) \| (.*?) \|$', l)
        if m and clean(m.group(1)) in LABELS: rows[LABELS[clean(m.group(1))]] = { 'th':clean(m.group(2)).replace('**', ''), 'en':clean(m.group(3)).replace('**', '') }
    assert len(rows) == 7, (key, list(rows)); helpers[key] = rows
out = ["// GENERATED by scripts/extract-rae-z4a.py from Output/Rae/2026-11-19-avegee-r2d-zone4-end.md (sections 1-2) - Rae's text verbatim, do not edit by hand (T9: two status notes of Rae's cut out of the EN of RAW_BOUTS · FB3-T8: the old tower name replaced, see the script).", ""]
out.append('export const RAW_Z4A_SCENES = Object.assign({}, ' + ', '.join('({\n' + b + '\n})' for b in blocks) + ');\n')
out.append('export const RAW_BOUTS = ' + json.dumps(bouts, ensure_ascii=False, indent=1) + ';\n')
out.append('export const RAW_HELPERS = ' + json.dumps(helpers, ensure_ascii=False, indent=1) + ';\n')
Path(__file__).resolve().parent.parent.joinpath('src', 'z4a-raw.js').write_text('\n'.join(out), encoding='utf-8')
print(len(blocks), 'blocks', sorted(bouts), list(helpers))
