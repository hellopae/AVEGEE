#!/usr/bin/env python3
"""T7b: copy the JS blocks of Rae's part C script (sections 3-5) VERBATIM into src/z3d-raw.js so the text is never retyped.
  python3 scripts/extract-rae-z3c.py "<path to Output/Rae/2026-11-19-avegee-r2c-zone3.md>"
Blocks are found by their first line; each is exported as a frozen constant (cases = one object, story groups = {key: scene}, page lists = array)."""
import sys, re
from pathlib import Path
L = Path(sys.argv[1]).read_text(encoding='utf-8').split('\n')
blocks = []; i = 0
while i < len(L):
    if L[i].startswith('```js') and i > 330:
        j = i + 1
        while not L[j].startswith('```'): j += 1
        blocks.append('\n'.join(L[i + 1:j])); i = j
    i += 1
def find(pred):
    for b in blocks:
        if pred(b): return b
    raise SystemExit('block not found')
def single(k): return find(lambda b: b.lstrip().startswith('{') and f"k:'{k}'" in b.split('\n')[1])
out = ["// GENERATED by scripts/extract-rae-z3c.py from Output/Rae/2026-11-19-avegee-r2c-zone3.md (sections 3-5) - Rae's text verbatim, do not edit by hand.", ""]
def put(name, body, kind): out.append(f"export const {name} = {'[' if kind == 'list' else '('}\n{body.rstrip().rstrip(',') if kind == 'list' else body}\n{']' if kind == 'list' else ')'};\n")
put('RAW_REDHOOD', single('redhood'), 'obj'); put('RAW_LOKIPRIEST', single('lokipriest'), 'obj'); put('RAW_GINGERWITCH', single('gingerwitch'), 'obj')
put('RAW_LOKI_STORIES', '{\n' + find(lambda b: b.startswith("'z3-loki-reveal'")) + '\n}', 'obj')
put('RAW_LOKI_SKILLS', '{\n' + find(lambda b: b.startswith('loki:[')) + '\n}', 'obj')
put('RAW_EIRLIN_WIN_PAGES', find(lambda b: b.lstrip().startswith("{ title:{ th:'ลังหอกที่ตรวจแล้ว'")), 'list')
put('RAW_SEV_COLLATERAL', '{\n' + find(lambda b: b.startswith("'z3-sev-collateral'")) + '\n}', 'obj')
put('RAW_HOME67', '{\n' + find(lambda b: b.startswith("'z3-home67-intro'")) + '\n' + find(lambda b: b.startswith("'z3-home67-join'")) + '\n}', 'obj')
Path(__file__).resolve().parent.parent.joinpath('src', 'z3d-raw.js').write_text('\n'.join(out), encoding='utf-8')
print('written', len(out))
