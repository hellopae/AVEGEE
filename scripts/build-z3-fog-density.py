#!/usr/bin/env python3
"""Z3 fog density map: where the frozen water, falls and gorges are, the fog is thick; on the paved plazas and roads it is thin.
Reads the zone 3 ground preview (img/map-zone3/v7/zone3-terrain-v7-preview.webp, read-only) and writes src/z3-fog-density.js:
a 48 x 32 grid, one hex digit (0-f) per cell, row by row. Nothing is drawn onto or filtered over the art; this only tells the fog where to gather."""
import sys
from PIL import Image, ImageFilter
import numpy as np
SRC='img/map-zone3/v7/zone3-terrain-v7-preview.webp'; OUT='src/z3-fog-density.js'; COLS,ROWS=48,32
a=np.asarray(Image.open(SRC).convert('RGB'),dtype=float)
r,g,b=a[...,0],a[...,1],a[...,2]
water=((b>r+80)&(g>r+45)&(b>140)).astype(float)               # saturated cyan = frozen river, falls, lake
m=Image.fromarray((water*255).astype('uint8')).filter(ImageFilter.GaussianBlur(24))
small=np.asarray(m.resize((COLS,ROWS),Image.BILINEAR),dtype=float)/255
d=np.clip(small/0.30,0,1)**0.75
# thin veil of mist at the very top of the map (the far ridge) so the horizon is not clean
top=np.clip(1-np.arange(ROWS)/ROWS*5,0,1)[:,None]*0.35
d=np.clip(.12+.88*d+top,0,1)
rows=[''.join('0123456789abcdef'[int(round(v*15))] for v in row) for row in d]
open(OUT,'w').write("""// Z3 fog density, generated by scripts/build-z3-fog-density.py from the zone 3 ground preview. Do not edit by hand.
// %d x %d cells over the whole zone 3 map, one hex digit per cell (0 = clear, f = thickest fog).
export const Z3_FOG_COLS=%d, Z3_FOG_ROWS=%d;
export const Z3_FOG_GRID=Object.freeze([\n%s\n]);
/** Fog density 0..1 at map fraction (u,v), bilinear over the grid. */
export function z3FogDensity(u,v){
  const x=Math.min(Z3_FOG_COLS-1.001,Math.max(0,u*Z3_FOG_COLS-.5)),y=Math.min(Z3_FOG_ROWS-1.001,Math.max(0,v*Z3_FOG_ROWS-.5));
  const x0=Math.floor(x),y0=Math.floor(y),fx=x-x0,fy=y-y0,at=(i,j)=>parseInt(Z3_FOG_GRID[j][i],16)/15;
  return (at(x0,y0)*(1-fx)+at(x0+1,y0)*fx)*(1-fy)+(at(x0,y0+1)*(1-fx)+at(x0+1,y0+1)*fx)*fy;
}
"""%(COLS,ROWS,COLS,ROWS,',\n'.join("  '%s'"%r for r in rows)))
print('mean density %.3f'%d.mean())
for row in rows: print(row)
